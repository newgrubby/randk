import type { Review } from './types';

/**
 * Отзывы учеников и родителей.
 *
 * МАССИВ ПУСТ НАМЕРЕННО. Вымышленные отзывы не создаются: подделка
 * социального доказательства — самый заметный признак дешёвого сайта
 * и прямой репутационный риск для центра.
 *
 * Два отзыва со старого сайта («Ольга» про поездку в Англию, «Виктор» про
 * китайский) не перенесены: авторство и актуальность не подтверждены.
 *
 * Как добавить: заполнить объект по типу `Review` и поставить
 * `confirmed: true`. Неподтверждённые отзывы не отображаются.
 * Настоятельно рекомендуется указывать `sourceUrl` — ссылка на VK или
 * Яндекс Карты повышает доверие сильнее самого текста.
 */
export const reviews: Review[] = [];

/** Отзывы, разрешённые к публикации. */
export const publishedReviews = reviews.filter((review) => review.confirmed);

export const hasPublishedReviews = publishedReviews.length > 0;
